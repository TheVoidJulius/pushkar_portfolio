// Generates supabase/seed.sql from supabase/seed-content.json.
// Usage: node scripts/generate-seed.mjs
// The JSON is the single source of placeholder content: it seeds the
// database AND is what the site falls back to when Supabase isn't configured.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const content = JSON.parse(readFileSync(path.join(root, "supabase/seed-content.json"), "utf8"));

const lit = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v) && v.every((x) => typeof x === "string")) {
    return `array[${v.map(lit).join(", ")}]::text[]`;
  }
  if (typeof v === "object") return `${lit(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

// Arrays that are empty need an explicit type
const arr = (v, isJson) => (Array.isArray(v) && v.length === 0 ? (isJson ? "'[]'::jsonb" : "'{}'::text[]") : lit(v));

const JSON_COLS = new Set(["stats", "highlights", "socials"]);

function upsertRow(table, row, conflict = "id") {
  const cols = Object.keys(row);
  const vals = cols.map((c) => (Array.isArray(row[c]) ? arr(row[c], JSON_COLS.has(c)) : lit(row[c])));
  const updates = cols.filter((c) => c !== conflict).map((c) => `${c} = excluded.${c}`);
  return `insert into public.${table} (${cols.join(", ")})\nvalues (${vals.join(", ")})\non conflict (${conflict}) do update set ${updates.join(", ")};\n`;
}

let sql = "-- AUTO-GENERATED by scripts/generate-seed.mjs from supabase/seed-content.json.\n";
sql += "-- Safe to re-run: every statement is an upsert.\n\n";

sql += upsertRow("site_settings", { id: 1, ...content.site });
sql += upsertRow("profiles", { id: 1, ...content.profile });
sql += upsertRow("about_content", { id: 1, ...content.about });
sql += upsertRow("contact_details", { id: 1, ...content.contact });
sql += upsertRow("assistant_settings", { id: 1, ...content.assistant });
sql += "\n";
for (const p of content.projects) sql += upsertRow("projects", p);
sql += "\n";
for (const { skills, ...cat } of content.skillCategories) {
  sql += upsertRow("skill_categories", cat);
  for (const s of skills) sql += upsertRow("skills", s);
}
sql += "\n";
for (const e of content.experiences) sql += upsertRow("experiences", e);

writeFileSync(path.join(root, "supabase/seed.sql"), sql);
console.log("Wrote supabase/seed.sql");
